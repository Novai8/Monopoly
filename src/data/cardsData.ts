export function drawCard(deck: 'event' | 'community', mode?: string): Card {
  const deckCards = deck === 'event' ? EVENT_CARDS : COMMUNITY_CARDS;
  if (mode === 'chaos') {
    const chaosCards = deckCards.filter((c) => c.category === 'chaos');
    if (chaosCards.length > 0 && Math.random() < 0.4) {
      return chaosCards[Math.floor(Math.random() * chaosCards.length)];
    }
  }
  return deckCards[Math.floor(Math.random() * deckCards.length)];
}
